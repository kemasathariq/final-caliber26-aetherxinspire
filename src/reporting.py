def write_json(data, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=False, default=str) + "\n", encoding="utf-8")


def _cell(value) -> str:
    if value is None or (not isinstance(value, (list, dict, str)) and pd.isna(value)):
        return ""
    if isinstance(value, float) and value == int(value) and abs(value) < 1e15:
        return f"{int(value):,}"
    if isinstance(value, float):
        return f"{value:,.4f}".rstrip("0").rstrip(".")
    if isinstance(value, int) and not isinstance(value, bool):
        return f"{value:,}"
    return str(value).replace("|", "\\|").replace("\n", " ")


def md_table(frame: pd.DataFrame, columns: list[str] | None = None) -> str:
    """Render a table as Markdown, with no extra dependency."""
    if frame.empty:
        return "_None._"
    columns = columns or list(frame.columns)
    lines = ["| " + " | ".join(columns) + " |", "| " + " | ".join("---" for _ in columns) + " |"]
    for values in frame[columns].astype(object).itertuples(index=False):
        lines.append("| " + " | ".join(_cell(v) for v in values) + " |")
    return "\n".join(lines)


def _header(title: str) -> list[str]:
    return [f"# {title}", "", f"**Data status:** {DATA_LABEL}", "",
            f"Generated by `src/pipeline.py`. Specification version {SPEC_VERSION}. "
            f"Assumed data cutoff {DATA_CUTOFF} (assumption A-01).", ""]


def write_dataset_profile(key: str, profile: dict, path: Path) -> None:
    spec = DATASETS[key]
    def part(name):
        table = profile[name]
        return table[table["dataset"] == spec.name]

    lines = _header(f"Data Profile: {spec.name}")
    columns = part("columns")
    lines += ["## Dimensions and worksheet", "",
              f"`{spec.file_name}`, worksheet `{spec.sheet}`: {len(profile['tables'][key]):,} data rows and {len(spec.columns)} source columns.",
              f"Documented grain, per the diagram: \"{spec.documented_grain}\". This is checked below, not assumed.", "",
              "## Columns, data types, missing values and unique values", "",
              md_table(columns, ["position", "source_column", "standard_name", "kind", "xlsx_cell_storage", "pandas_dtype",
                                 "missing", "missing_pct", "unique_values", "leading_trailing_space_rows"]), "",
              "## Duplicate records", "", md_table(profile["duplicates"][profile["duplicates"]["dataset"] == key],
                                                   ["total_rows", "distinct_rows", "extra_copies", "extra_copies_pct", "groups_with_copies",
                                                    "occurrence_distribution", "adjacent_copy_gaps", "median_copy_gap_rows"]), "",
              "Repeated rows are labelled, never removed. Whether they are errors is not established.", ""]
    if key == "prpo":
        lines += ["## PR PO views", ""]
        for name in (ORIGINAL, DISTINCT):
            lines += [f"- **{name}.** {VIEW_DEFINITIONS[name]['definition']} Limitation: {VIEW_DEFINITIONS[name]['limitation']}"]
        lines += ["", "Each value below belongs to the named view. The columns are alternatives and are never added together. "
                  "Intervals use requested or promised dates; no actual receipt date exists.", "",
                  md_table(profile["view_comparison"]), ""]
    numeric = part("numeric")
    if not numeric.empty:
        lines += ["## Numerical summaries", "", "Summarised within one unit or currency only.", "",
                  md_table(numeric, ["view", "grain", "column", "group", "count", "min", "median", "p95", "max", "mean", "zero_count", "non_integer_count"]), ""]
    dates = part("dates")
    if not dates.empty:
        lines += ["## Date ranges", "", md_table(dates, ["view", "column", "non_null", "missing", "distinct_dates", "min_date", "max_date",
                                                         "with_time_component", "after_data_cutoff"]), ""]
    categories = part("categories")
    if not categories.empty:
        limited = categories[categories["rank"] <= 15]
        lines += ["## Categorical distributions", "", "Top 15 values per column. The full list is in `outputs/tables/categorical_distribution.csv`.", "",
                  md_table(limited, ["view", "column", "rank", "value", "count", "pct"]), ""]
    keys = part("primary_keys")
    lines += ["## Candidate primary keys", "",
              "Tested on identifier and date columns, alone and combined. Combinations with dates can be unique by chance and are not business keys.", "",
              md_table(keys[keys["includes_date"] == False], ["columns", "repeats_on_all_rows", "repeats_on_distinct_rows", "contains_nulls", "assessment"]), "",
              f"Combinations that include a date and happen to be unique: {int((keys['assessment'] == 'coincidental_unique_includes_date').sum())}. See `outputs/tables/candidate_primary_keys.csv`.", ""]
    foreign = profile["foreign_keys"]
    involved = foreign[foreign["column_a"].str.startswith(key + ".") | foreign["column_b"].str.startswith(key + ".")]
    lines += ["## Candidate foreign keys", "", "Value-set comparison. No tables were joined.", "",
              md_table(involved, ["column_a", "column_b", "shared_values", "coverage_of_a_pct", "coverage_of_b_pct",
                                  "observed_cardinality_a_to_b", "raw_inner_join_rows", "diagram_relation", "assessment"]), ""]
    findings = profile["findings"]
    relevant = findings[findings["dataset"].str.contains(spec.name, regex=False)]
    lines += ["## Potential data quality issues", "", md_table(relevant, ["finding_id", "field", "finding", "count", "view_or_grain", "treatment", "related_definition"]), ""]
    path.write_text("\n".join(lines), encoding="utf-8")


