def write_validation_report(results: pd.DataFrame, path: Path) -> None:
    counts = results["status"].value_counts()
    lines = _header("Validation Report")
    lines += [f"**Overall:** {int(counts.get('PASS', 0)):,} passed, {int(counts.get('FAIL', 0)):,} failed, {int(counts.get('WARN', 0)):,} warnings, out of {len(results):,} checks.", "",
              f"**Checksum scope:** {BASELINE_NOTE}", "",
              "**Reading these results.** The `expected values` group shows the data has not drifted from documented counts. "
              "It does not show that an interpretation of those counts is correct.", "",
              "## Results by group", ""]
    summary = (results.groupby(["group", "status"]).size().unstack(fill_value=0)
               .reindex(columns=["PASS", "FAIL", "WARN"], fill_value=0).reset_index())
    lines += [md_table(summary), "", "## Failed checks and warnings", ""]
    problems = results[results["status"] != "PASS"]
    lines += [md_table(problems, ["check_id", "dataset", "description", "expected", "observed", "severity", "status", "source"]), ""]
    lines += ["All check results are in `outputs/tables/validation_results.csv`.", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def write_duplicate_evidence_report(evidence: dict, sensitivity: pd.DataFrame, shared_orders: pd.DataFrame, duplicate_summary: pd.DataFrame, path: Path) -> None:
    """PR PO and Movement duplicate evidence. It reports tests and states no cause."""
    keys = pd.DataFrame([{"measure": k, "value": v} for k, v in evidence["keys"].items()])
    per_material = sensitivity[sensitivity["group"] == "per material"]
    totals = sensitivity[(sensitivity["group"] != "per material") & (sensitivity["metric"] != "issue_lines_in_month")]
    months = sensitivity[sensitivity["metric"] == "issue_lines_in_month"]
    totals_text = {"same_notification_date": int(shared_orders["same_notification_date"].sum()), "issue_rows": int(shared_orders["issue_rows"].sum()),
                   "one": int(shared_orders["issue_rows_material_in_exactly_one_location_bom"].sum()), "none": int(shared_orders["issue_rows_material_in_no_location_bom"].sum())}
    lines = _header("Duplicate Evidence")
    lines += ["**Cause of repeated rows: Cannot be confirmed from the available data or documentation.** These tests show what copy counts do or do not relate to. "
              "They choose no policy. PR PO keeps both approved views.", "",
              "## Exact duplicates by dataset", "", md_table(duplicate_summary, ["dataset", "total_rows", "distinct_rows", "extra_copies", "extra_copies_pct", "adjacent_copy_gaps", "copy_gaps", "median_copy_gap_rows"]), "",
              "## PR PO: key structure", "", md_table(keys), "",
              "## PR PO: is a copy count shared within a document?", "",
              "If whole documents were repeated, lines of one document would share a copy count far more often than random assignment. "
              "Calculated on `exact_distinct_rows`, using documents with more than one line.", "", md_table(evidence["permutations"]), "",
              "## PR PO: copy count against numeric fields", "", "Spearman rank correlation. Amounts stay within IDR and quantities within one unit.", "", md_table(evidence["numeric"]), "",
              "## PR PO: copy count against categories", "",
              "Chi-square with a Holm correction across the seven tests. Where many cells have an expected count below 5, the p-value is approximate.", "", md_table(evidence["categorical"]), "",
              "## Movement: all rows compared with exact-distinct rows", "", "No Movement policy is applied. Quantities stay within one unit or one material.", "", md_table(totals, ["metric", "group", "all_rows", "exact_distinct_rows", "change_pct"]), "",
              "Per-material effect:", "", md_table(per_material, ["metric", "value"]), "",
              f"Monthly issue lines fall by between {abs(months['change_pct'].max()):.2f}% and {abs(months['change_pct'].min()):.2f}% in the distinct view.", "",
              "## Orders on two notifications", "",
              f"{len(shared_orders)} orders. {totals_text['same_notification_date']} have both notifications on one date. They cover {totals_text['issue_rows']} issue rows. "
              f"On {totals_text['one']} of those rows the material is on the BoM of exactly one of the two locations, and on {totals_text['none']} it is on neither. "
              "This is reported only. No allocation rule is applied. The list is in `outputs/exceptions/shared_orders.csv`.", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


