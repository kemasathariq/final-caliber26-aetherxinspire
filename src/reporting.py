def write_mart_summary(metadata: dict, marts: dict, measures: dict, path: Path) -> None:
    """Generated overview of M1 to M3. No value here is a recommendation."""
    inventory = pd.DataFrame([{"table": name, "grain": entry["grain"], "primary_key": " + ".join(entry["primary_key"]), "rows": entry["rows"], "columns": len(entry["columns"])} for name, entry in metadata["tables"].items()])
    comparison = marts["tables"]["mart_material_demand_comparison"]
    tiers = comparison.groupby("impact_tier").agg(materials=("material_no", "size"), low_line_count=("flag_low_line_count", "sum")).reset_index()
    stock = marts["tables"]["mart_material_inventory"]
    gaps = stock.assign(missing=stock["simulation_inputs_missing"].fillna("none"), mrp=stock["mrp_type"].astype("string")).groupby(["mrp", "missing"]).size().reset_index(name="materials")
    lines = _header("Mart Summary: M1 to M3")
    lines += ["No view or scenario is the default, and none is the true value.", "", "## Tables", "", md_table(inventory), "",
              "## M1: amounts by currency", "", "Each currency stands alone. The two views are alternatives and are never added together.", "", md_table(marts["currency_summary"]), "",
              "## M3: scenarios by unit", "", "Quantities stay within one unit. No total exists across units.", "", md_table(marts["unit_scenario_summary"]), "",
              "## M3: impact of the scenario choice by material", "", md_table(tiers), "", "Threshold sensitivity:", "", md_table(marts["impact_sensitivity"]), "",
              "Materials at or above the material threshold are listed in `outputs/exceptions/demand_materially_affected.csv`.", "",
              "## M2: requested against issued quantity", "", "Materials present in both, within one unit. No receipts or dated stock exist, so this is a plausibility comparison and not a stock balance.", "", md_table(marts["procurement_issue_reconciliation"]), "",
              "## M2: inputs a later simulation lacks", "", "Having a value does not confirm its meaning. Definitions remain open.", "", md_table(gaps), ""]
    path.write_text("\n".join(lines), encoding="utf-8")


